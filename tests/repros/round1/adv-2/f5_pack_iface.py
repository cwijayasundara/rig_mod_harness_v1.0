# §5 Protocols transcribed verbatim (bodies elided); a core V3 runner that only uses them.
from typing import Protocol, Any
from pathlib import Path
class SourcePack(Protocol):
    id: str
    def detect(self, root: Path) -> Any: ...
    def parse(self, root: Path) -> Any: ...
    def entry_points(self, g: Any) -> Any: ...
    def build(self, ws: Any) -> Any: ...
    def run_unit(self, unit: Any, inputs: Any) -> Any: ...
    def record_io(self, entry: Any) -> Any: ...
    def input_generators(self, unit: Any) -> Any: ...
class TargetPack(Protocol):
    id: str
    def scaffold(self, layout: Any) -> Any: ...
    def build(self, ws: Any) -> Any: ...
    def test(self, ws: Any, selector: str) -> Any: ...
    def arch_rules(self, adrs: Any) -> Any: ...
    def mutation(self, ws: Any, scope: str) -> Any: ...
    def recipes(self) -> Any: ...
    def antistub_patterns(self) -> Any: ...
class DataPack(Protocol):
    def extract(self, store: Any) -> Any: ...
    def canonicalize(self, record: bytes, layout: Any) -> dict: ...
    def reconcile(self, a: Any, b: Any, policy: Any) -> Any: ...
def members(p): return sorted(k for k in vars(p) if not k.startswith('_'))
print('TargetPack members:', members(TargetPack))
print('TargetPack has run_unit/record_io/input_generators:', [hasattr(TargetPack,m) for m in ('run_unit','record_io','input_generators')])
print('DataPack has a load/write method:', [m for m in members(DataPack) if m in ('load','write','migrate')])
def core_v3(src: SourcePack, tgt: TargetPack, unit, inputs):      # T step: legacy vs modern on same inputs
    return src.run_unit(unit, inputs), tgt.run_unit(unit, inputs)
def core_v3_restructure(before: TargetPack, after: TargetPack, unit, inputs):  # R step: Java -> Java
    return before.run_unit(unit, inputs), after.run_unit(unit, inputs)
class Src:
    id='cobol-zos'
    def run_unit(self,u,i): return b'legacy-out'
class Tgt:
    id='java21-spring3'
    def scaffold(self,l): ...
    def build(self,w): ...
    def test(self,w,s): return 'junit-xml'
    def arch_rules(self,a): ...
    def mutation(self,w,s): ...
    def recipes(self): return []
    def antistub_patterns(self): return []
for f,args in ((core_v3,(Src(),Tgt())),(core_v3_restructure,(Tgt(),Tgt()))):
    try: print(f.__name__, '->', f(*args,'CBACT04C',{}))
    except AttributeError as e: print(f.__name__, '-> AttributeError:', e)
